//* append propery to the end of an existing vtk file
//* the property can be scalar or vector
//* the row is the number of cells
//* the column is the dimension of property
template <typename DerivedV,
          typename DerivedF,
          typename DerivedX>
int append_vtk_with_attribute(
    const std::string &file_name,
    const Eigen::MatrixBase<DerivedV> &V,
    const Eigen::MatrixBase<DerivedF> &C,
    const Eigen::MatrixBase<DerivedX> &property,
    const std::string &name = "cell_property") {

    //* deal with empty property
    if (property.size() == 0) {
        return 0;
    }

    std::ofstream ofs(file_name, std::ios_base::app);
    if (!ofs) {
        std::cerr << "vtk file create error " << file_name << std::endl;
    }
    std::string data_type, data_dimension;
    //* judge cell or point data
    {
        if (property.rows() == V.rows()) {
            data_type = "POINT_DATA " + std::to_string(property.rows()) + '\n';
        } else if (property.rows() == C.rows()) {
            data_type = "CELL_DATA " + std::to_string(property.rows()) + '\n';
        } else {
            std::cerr << "property number error " << std::endl;
            exit(-1);
        }
    }
    //* judge vector or scalar
    {
        if (property.cols() == 1) {
            data_dimension = "SCALARS " + name + " double 1\n LOOKUP_TABLE default \n";
        } else if (property.cols() == 3) {
            data_dimension = "VECTORS " + name + " double\n";
        } else {
            std::cerr << "property dimension error " << std::endl;
            exit(-1);
        }
    }

    ofs << data_type << data_dimension;
    const int rows = property.rows();
    for (int i = 0; i < rows; i++) {
        ofs << property.row(i) << std::endl;
    }
    ofs.close();
    return 0;
}

template <vtk_file_t file_type = vtk_file_t::surface,
          typename DerivedV,
          typename DerivedF,
          typename DerivedX>
int write_vtk_with_attribute(
    const std::string &file_name,
    const Eigen::MatrixBase<DerivedV> &V,
    const Eigen::MatrixBase<DerivedF> &C,
    const Eigen::MatrixBase<DerivedX> &property,
    const std::string &name = "cell_property") {

    write_vtk<file_type>(file_name, V, C);
    append_vtk_with_attribute(file_name, V, C, property, name);

    return 0;
}

template <vtk_file_t file_type = vtk_file_t::surface,
          typename DerivedV,
          typename DerivedF>
int append_vtk_with_attribute(
    const std::string &file_name,
    const Eigen::MatrixBase<DerivedV> &V,
    const Eigen::MatrixBase<DerivedF> &C,
    const std::vector<vtk_property> &properties) {
    using namespace std;
    using namespace Eigen;

    std::ofstream ofs(file_name, std::ios_base::app);
    if (!ofs) {
        std::cerr << "vtk file create error " << file_name << std::endl;
    }

    const int nv = V.rows();
    const int nf = C.rows();

    const int np = properties.size();
    vector<int> v_property;
    vector<int> c_property;
    for (int pi = 0; pi < np; pi++) {
        if (properties[pi].data.size() == nv) {
            v_property.push_back(pi);
        } else if (properties[pi].data.size() == nf) {
            c_property.push_back(pi);
        }
    }

    //* write vertex property
    if (v_property.size() > 0) {
        ofs << "POINT_DATA " << nv << std::endl;
        for (int vpi : v_property) {
            const auto &property = properties[vpi];
            ofs << "SCALARS " << property.name << " double 1\n LOOKUP_TABLE default \n";
            for (int i = 0; i < nv; i++) {
                ofs << property.data[i] << std::endl;
            }
        }
    }

    //* write cell property
    if (c_property.size() > 0) {
        ofs << "CELL_DATA " << nf << std::endl;
        for (int cpi : c_property) {
            const auto &property = properties[cpi];
            ofs << "SCALARS " << property.name << " double 1\n LOOKUP_TABLE default \n";
            for (int i = 0; i < nf; i++) {
                ofs << property.data[i] << std::endl;
            }
        }
    }

    return 0;
}

template <vtk_file_t file_type = vtk_file_t::surface,
          typename DerivedV,
          typename DerivedF>
int write_vtk_with_attribute(
    const std::string &file_name,
    const Eigen::MatrixBase<DerivedV> &V,
    const Eigen::MatrixBase<DerivedF> &C,
    const std::vector<vtk_property> &properties) {

    write_vtk<file_type>(file_name, V, C);
    append_vtk_with_attribute<file_type>(file_name, V, C, properties);

    return 0;
}

