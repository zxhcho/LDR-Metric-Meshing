//* write vtk with pure mesh type
template <vtk_file_t file_type = vtk_file_t::surface,
          typename DerivedV,
          typename DerivedF>
int write_vtk(
    const std::string &file_name,
    const Eigen::MatrixBase<DerivedV> &V,
    const Eigen::MatrixBase<DerivedF> &C) {

    using namespace std;

    ofstream ofs(file_name);
    if (!ofs) {
        cerr << "vtk file create error: " << file_name << endl;
        return __LINE__;
    }
    const size_t num_points = V.rows();
    const size_t num_cells = C.rows();
    const size_t num_cell_points = C.cols();
    size_t point_list_size = C.rows() * (num_cell_points + 1);

    // file header
    ofs << "# vtk DataFile Version 3.0" << endl
        << "Mesh Generated by file_io" << endl
        << "ASCII" << endl
        << "DATASET UNSTRUCTURED_GRID" << endl
        << "POINTS " << num_points << " double" << endl;

    // point data
    for (size_t i = 0; i < num_points; i++) {
        ofs << V.row(i) << endl;
    }

    // face structure
    ofs << "CELLS " << num_cells << ' ' << point_list_size << endl;
    for (size_t i = 0; i < num_cells; i++) {
        ofs << num_cell_points << ' ' << C.row(i) << endl;
    }

    // cell types
    ofs << "CELL_TYPES " << num_cells << endl;
    for (size_t i = 0; i < num_cells; i++) {
        if (file_type == vtk_file_t::surface) {
            ofs << surface_cell_t.at(num_cell_points) << endl;
        } else {
            ofs << volumn_cell_t.at(num_cell_points) << endl;
        }
    }
    ofs.close();

    return 0;
}

//* write vtk with pure surface mesh type
template <typename DerivedV,
          typename DerivedF>
int write_surface_vtk(
    const std::string &file_name,
    const Eigen::MatrixBase<DerivedV> &V,
    const Eigen::MatrixBase<DerivedF> &C) {
    return write_vtk<vtk_file_t::surface>(file_name, V, C);
}

